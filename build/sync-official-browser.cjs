'use strict'
const fs = require('node:fs')
const path = require('node:path')
const { stripTypeScriptTypes } = require('node:module')
const root = path.resolve(__dirname, '..')
const vendor = path.join(root, 'vendor/deepseek-desktop')
const check = process.argv.includes('--check')
const normalize = source => source.replace(/\r\n/g, '\n')
const read = name => normalize(fs.readFileSync(path.join(vendor, 'src', name + '.ts'), 'utf8'))
const ipc = Object.fromEntries([...read('ipc').matchAll(/^  ((?:browser|shortcuts)\w+): '([^']+)'/gm)].map(([, key, value]) => [key, value]))
const header = '// Generated by build/sync-official-browser.cjs; source and MIT license: vendor/deepseek-desktop.\n'

/** Generate committed CommonJS and sandbox-preload code from the pinned official sources. */
function write(file, text) {
  if (check) {
    if (normalize(fs.readFileSync(file, 'utf8')) !== text) throw new Error('Generated source differs: ' + file)
  } else fs.writeFileSync(file, text)
}
function compile(source) {
  return stripTypeScriptTypes(source, { mode: 'transform' }).trim() + '\n'
}
function commonjs(name, exported) {
  let source = read(name).replace(/^import type .*\n/gm, '')
    .replace(/^import \{ (.*?) \} from '([^']+)'\r?$/gm, (_line, fields, specifier) => {
      fields = fields.split(', ').filter(field => !field.startsWith('type ')).join(', ')
      if (specifier === './ipc.ts') return `const { ${fields} } = require('../../desktop-browser-ipc.js')`
      if (specifier.startsWith('@deepseek-ai/')) return `const { ${fields} } = require('../../desktop-browser-runtime.js').load('${specifier}')`
      return `const { ${fields} } = require('${specifier.replace(/\.ts$/, '.js')}')`
    }).replace('export class ', 'class ').replace('export function ', 'function ')
  if (name === 'keyboard') source = source.replace("window.webContents.mainFrame.url.startsWith('dsh-app://app/')", 'isDesktopSender(window.webContents, window.webContents.mainFrame)')
    .replace('const { DESKTOP_IPC, assertDesktopSender }', 'const { DESKTOP_IPC, assertDesktopSender, isDesktopSender }')
  write(path.join(vendor, name + '.js'), header + "'use strict'\n" + compile(source) + `module.exports = { ${exported} }\n`)
}
commonjs('browser-guests', 'DesktopBrowserGuests')
commonjs('keyboard', 'installDesktopShortcuts')
commonjs('keybindings', 'desktopKeybindings')
write(path.join(vendor, 'channels.json'), JSON.stringify(ipc, null, 2) + '\n')

const bridge = read('preload-browser').replace(/^import .*\n/gm, '').replace('export function ', 'function ')
const product = read('preload-app')
const start = product.indexOf('function createProductApi()')
const end = product.indexOf('    updates:', start)
if (start < 0 || end < 0) throw new Error('Official preload API boundary changed')
const api = product.slice(start, end).replace('createProductApi()', 'createDesktopBrowserApi()')
  .replace(/^    deviceInfo:.*\n/m, '') + '  }\n}\n'
const generated = header + `const DESKTOP_IPC = ${JSON.stringify(ipc, null, 2)}\n` + compile(bridge + '\n' + api)
const preload = path.join(root, 'preload-desktop.js')
const source = normalize(fs.readFileSync(preload, 'utf8'))
const begin = '// BEGIN OFFICIAL BROWSER BRIDGE'
const finish = '// END OFFICIAL BROWSER BRIDGE'
const region = `${begin}\n${generated}${finish}`
const next = source.includes(begin)
  ? source.slice(0, source.indexOf(begin)) + region + source.slice(source.indexOf(finish) + finish.length)
  : source.replace("const initialState =", region + '\n\nconst initialState =')
write(preload, next)
console.log(check ? 'PASS: official browser sources are synchronized' : 'Official browser sources synchronized')
